export async function generateWire() {
  const header =
    [
      "// Generated by scripts/generate-wire.ts",
      "#pragma once",
      "namespace wire {",
      `constexpr int version = ${protocol.version};`,
      ...Object.entries(protocol.kinds).map(
        ([name, id]) => `constexpr int k_${name} = ${id};`,
      ),
      ...Object.entries(protocol.directions).map(
        ([name, id]) => `constexpr int d_${name} = ${id};`,
      ),
      ...Object.entries(protocol.severities).map(
        ([name, id]) => `constexpr int s_${name} = ${id};`,
      ),
      "}",
    ].join("\n") + "\n";
  const ts = `// Generated by scripts/generate-wire.ts\nexport const wire = ${JSON.stringify(protocol, null, 2)} as const;\n`;
  for (const [relative, text] of [
    ["aidl-cpp/src/generated/wire.h", header],
    ["aidl-parser/src/generated/wire.ts", ts],
  ]) {
    const path = new URL(`../${relative}`, import.meta.url);
    await mkdir(dirname(fileURLToPath(path)), { recursive: true });
    if ((await readFile(path, "utf8").catch(() => "")) !== text)
      await writeFile(path, text);
  }
}
if (import.meta.main) await generateWire();
